export type CopyKey = keyof typeof copy;
export function useT() {
  const language = useContext(LocaleContext);
  return (key: CopyKey) => copy[key][language === 'en' ? 1 : 0];
}

const statuses: Record<string, readonly [string, string]> = {
  READY: ['Sẵn sàng', 'Ready'],
  RUNNING: ['Đang chạy', 'Running'],
  PAUSED: ['Tạm dừng', 'Paused'],
  COMPLETED: ['Hoàn thành', 'Completed'],
  ABANDONED: ['Bỏ dở', 'Abandoned'],
  EXPIRED: ['Hết hạn', 'Expired'],
  FAILED: ['Thất bại', 'Failed'],
};
export function useStatusLabel() {
  const language = useContext(LocaleContext);
  return (status: string) =>
    statuses[status]?.[language === 'en' ? 1 : 0] ?? status;
}
